const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const ctx = { console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('AuthService.js', 'utf8'), ctx);
let mode = 'OPEN';
const user = {user_id:'seller-1',email:'seller'};
ctx.getUserAccessMode = () => mode;
ctx.ensureApplicationSheets_ = () => {};
ctx.isAnonymousFeedbackEnabled = () => true;
ctx.validateUserSession_ = token => token === 'valid' ? {user} : null;
ctx.findAdminForSeller_ = () => null;
assert.equal(ctx.getPublicAccessState('').loginRequired, false);
assert.equal(ctx.requireChatAccess_(''), null);
assert.equal(ctx.requireChatAccess_('expired'), null);
assert.equal(ctx.requireChatAccess_('valid'), user);
mode = 'LOGIN_REQUIRED';
assert.equal(ctx.getPublicAccessState('').loginRequired, true);
assert.throws(() => ctx.requireChatAccess_(''), /로그인이 필요/);
assert.throws(() => ctx.requireChatAccess_('expired'), /로그인이 필요/);
assert.equal(ctx.requireChatAccess_('valid'), user);
const stored = { USER_ACCESS_MODE: 'OPEN' };
const props = {getProperty: k => stored[k] ?? null, setProperties: values => Object.assign(stored, values)};
const configCtx = {PropertiesService:{getScriptProperties:()=>props}, LockService:{getScriptLock:()=>({waitLock(){},releaseLock(){}})}};
vm.createContext(configCtx);
vm.runInContext(fs.readFileSync('Config.js','utf8'), configCtx);
assert.equal(configCtx.getUserAccessMode(), 'LOGIN_REQUIRED');
stored.USER_ACCESS_MODE = 'OPEN';
assert.equal(configCtx.getUserAccessMode(), 'OPEN');
console.log('chat access policy tests passed');
